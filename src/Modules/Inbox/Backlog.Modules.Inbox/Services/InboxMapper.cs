using Backlog.Modules.Inbox.Abstractions.DataTransferObjects;
using Backlog.Modules.Inbox.Abstractions.Services;
using Backlog.Modules.Inbox.DomainModels;

namespace Backlog.Modules.Inbox.Services;

/// <summary>
/// Turns the aggregates into the shapes callers are allowed to hold. One place,
/// so a field added to an item is a deliberate decision to publish it rather
/// than something that leaks out of whichever handler happened to be edited —
/// which is how the two sync flags stay unpublished.
/// </summary>
internal static class InboxMapper
{
    /// <summary>The item as callers hold it. <paramref name="transcriptionFailures"/>, by
    /// sha256, are the recordings waiting for Retry; the snapshot the pane draws passes them,
    /// so a recording row can say its transcription failed.</summary>
    public static InboxItemDto ToDto(this InboxItem item, IReadOnlyDictionary<string, InboxTranscriptionFailureDto>? transcriptionFailures = null) => new(
        item.Id,
        item.Title,
        item.BodyMd,
        item.SourceUrl,
        item.CapturedAt,
        item.ReceivedAt,
        item.Status,
        item.Kind,
        item.KindSlug,
        item.Source.Channel,
        item.Source.Person,
        [.. item.Tags.Select(tag => new InboxTagDto(tag.Name, tag.AutoGenerated))],
        [.. item.RepoIds],
        item.ListId,
        item.Routing is { } routing
            ? new InboxRoutingDto(routing.Domain, routing.RepoIds, routing.TaskIds, routing.RoutedAt) { EventId = routing.EventId }
            : null,
        item.DeferredUntil)
    {
        Attachments = [.. item.Attachments.Select(attachment => new InboxAttachmentDto(
            attachment.Id,
            attachment.Name,
            attachment.ContentType,
            attachment.SizeBytes,
            attachment.IsImage,
            attachment.IsDownloaded,
            attachment.LastError)
        {
            LocalPath = attachment.IsDownloaded ? attachment.LocalPath : null,
            TranscriptionFailure = attachment.IsRecording && transcriptionFailures?.GetValueOrDefault(attachment.Sha256) is { WaitsForRetry: true } failure
                ? failure
                : null,
        })],
        DuplicateOf = item.DuplicateOf,
        DuplicateOfTask = item.DuplicateOfTask,
    };

    public static InboxListDto ToDto(this InboxList list) => new(list.Id, list.Name, list.GroupId, list.Order);

    public static InboxGroupDto ToDto(this InboxGroup group) => new(group.Id, group.Name, group.Order);
}
