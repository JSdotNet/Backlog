using Backlog.Modules.Inbox.Abstractions;

namespace Backlog.Modules.Inbox.DomainModels;

/// <summary>
/// Where a capture came from: the channel it arrived through and, when the
/// channel knows, the person behind it. <paramref name="Person"/> keeps its
/// <c>@</c>, the same way a person tag is stored in Tasks — the sigil is what
/// says "a person" and stripping it would need putting back at every reader.
/// </summary>
public sealed record InboxSource(string Channel, string? Person);

/// <summary>
/// One tag on an item, stored bare (no <c>#</c>) and compared by name without
/// regard to case, so <c>Deploy</c> and <c>deploy</c> are one tag rather than
/// two chips. Equality deliberately ignores <see cref="AutoGenerated"/>: a tag
/// a person then typed by hand is the same tag, now theirs.
/// </summary>
public sealed record InboxTag(string Name, bool AutoGenerated)
{
    public bool Equals(InboxTag? other) =>
        other is not null && string.Equals(Name, other.Name, StringComparison.OrdinalIgnoreCase);

    public override int GetHashCode() => StringComparer.OrdinalIgnoreCase.GetHashCode(Name);
}

/// <summary>
/// Where a triaged item went. Written once, when the item routes, and never
/// edited: it is the record of a decision, not a live link. <paramref name="TaskIds"/>
/// name aggregates in another context that may since have been deleted there,
/// which is why they are ids and not references. <paramref name="EventId"/> is the
/// knowledge event a route To Event made, for the same reason an id.
/// </summary>
public sealed record RoutingTarget(
    RoutingDomain Domain,
    IReadOnlyList<string> RepoIds,
    IReadOnlyList<Guid> TaskIds,
    DateTimeOffset RoutedAt,
    Guid? EventId = null);

/// <summary>One end of an edition as the capture wrote it: the day, and a time
/// with its UTC offset only when the source gave them. Equality is by value.</summary>
public sealed record InboxEventDate(DateOnly Date, TimeOnly? Time, TimeSpan? Offset);

/// <summary>
/// The dates, place and watched page an event page capture found, mirrored from
/// Capture's Event Facts (<c>.devbook/domain/inbox/domain.md#event-facts</c>). The
/// item keeps them as provenance, unchanged, and hands them over when it is routed
/// To Event. Equality is by value.
/// </summary>
public sealed record InboxEventFacts(
    InboxEventDate? Start,
    InboxEventDate? End,
    string? Place,
    string? PageUrl,
    string? PageTitle)
{
    /// <summary>True when the capture found nothing at all, which is no facts.</summary>
    public bool IsEmpty =>
        Start is null && End is null
        && string.IsNullOrWhiteSpace(Place) && string.IsNullOrWhiteSpace(PageUrl) && string.IsNullOrWhiteSpace(PageTitle);
}
