using Backlog.Modules.Inbox.Abstractions;
using Backlog.Modules.Inbox.DomainModels;

namespace Backlog.Modules.Inbox.UnitTests;

/// <summary>
/// The phone's edit of a capture, as the aggregate takes it: the later copy's
/// title and body replace the open item's, and nothing the desktop set on the
/// item, nor what the capture was, moves.
/// </summary>
public sealed class CaptureEditTests
{
    private static readonly DateTimeOffset Edited = Items.Noon.AddMinutes(30);

    [Fact]
    public void A_later_edit_of_an_open_capture_replaces_its_title_and_body_and_nothing_else()
    {
        var item = InboxItem.FromCapture(
            Guid.CreateVersion7(), "Aspire walkthrough https://example.com/a", new InboxSource("mobile", Person: null),
            "https://example.com/a", ContentKind.Link, Items.Noon, Items.Noon.AddMinutes(5));
        var listId = Guid.CreateVersion7();
        item.MoveToList(listId);
        item.SetTags([new InboxTag("video", AutoGenerated: false)]);
        item.SetKind(ContentKind.Link, "link");

        var applied = item.ApplyCaptureEdit("Aspire 13   walkthrough\nfor the team", "  Watch before Friday.  ", Edited);

        Assert.True(applied);
        Assert.Equal("Aspire 13 walkthrough for the team", item.Title);
        Assert.Equal("Watch before Friday.", item.BodyMd);
        Assert.Equal(Edited, item.EditedAt);
        Assert.Equal(Items.Noon, item.CapturedAt);
        Assert.Equal("https://example.com/a", item.SourceUrl);
        Assert.Equal(ContentKind.Link, item.Kind);
        Assert.Equal(listId, item.ListId);
        Assert.Equal("video", Assert.Single(item.Tags).Name);
        Assert.Equal(InboxStatus.Unprocessed, item.Status);
        Assert.False(item.ReplicaAckPending);
    }

    [Fact]
    public void An_edit_of_a_deferred_capture_is_taken_too()
    {
        var item = Items.FromPhone();
        item.Defer(DateOnly.FromDateTime(Items.Noon.AddDays(3).Date), Items.Noon.AddMinutes(6));

        Assert.True(item.ApplyCaptureEdit("Call the dentist about the crown", null, Edited));
        Assert.Equal("Call the dentist about the crown", item.Title);
        Assert.Equal(string.Empty, item.BodyMd);
        Assert.Equal(InboxStatus.Deferred, item.Status);
    }

    /// <summary>The replay of the copy already taken, or an older one: nothing
    /// changes. The stamp is the service's, so equal means the same version.</summary>
    [Theory]
    [InlineData(0)]
    [InlineData(-1)]
    public void An_edit_stamped_at_or_before_the_copy_held_changes_nothing(int minutes)
    {
        var item = Items.FromPhone();
        item.ApplyCaptureEdit("Call the dentist about the crown", null, Edited);

        Assert.False(item.ApplyCaptureEdit("Older words", "older", Edited.AddMinutes(minutes)));
        Assert.Equal("Call the dentist about the crown", item.Title);
        Assert.Equal(Edited, item.EditedAt);
    }

    /// <summary>A copy the service restamped without rewording — a retried push,
    /// a file added — is not an edit: nothing changes and nothing is reported, so
    /// no "edited" line appears for words the person never changed.</summary>
    [Fact]
    public void A_later_copy_with_the_same_words_is_not_an_edit()
    {
        var item = Items.FromPhone();
        item.ApplyCaptureEdit("Call the dentist about the crown", "Thursday.", Edited);

        Assert.False(item.ApplyCaptureEdit("Call the dentist  about the crown", " Thursday. ", Edited.AddMinutes(5)));
        Assert.Equal(Edited, item.EditedAt);
    }

    /// <summary>Decided is decided: the phone's words arriving after the item was
    /// routed or archived change neither the item nor what it became.</summary>
    [Theory]
    [InlineData("archived")]
    [InlineData("routed")]
    public void An_edit_of_a_decided_capture_changes_nothing(string decision)
    {
        var item = Items.FromPhone();
        if (decision == "archived") item.Archive(Items.Noon.AddMinutes(10));
        else item.RouteToBacklog([Guid.CreateVersion7()], [], Items.Noon.AddMinutes(10));

        Assert.False(item.ApplyCaptureEdit("Reworded", null, Edited));
        Assert.Equal("Call the dentist", item.Title);
    }

    /// <summary>Only a replica capture has a phone behind it that may reword it;
    /// a feed's or this desktop's own item is not edited this way.</summary>
    [Fact]
    public void An_edit_of_an_item_with_no_replica_behind_it_changes_nothing()
    {
        var item = Items.Manual();

        Assert.False(item.ApplyCaptureEdit("Reworded", null, Edited));
        Assert.Equal("Call the dentist", item.Title);
    }

    /// <summary>A note syncs both ways through its own path
    /// (<see cref="InboxItem.ApplyNote"/>), never this one.</summary>
    [Fact]
    public void A_note_is_refused()
    {
        var note = InboxItem.FromCapture(
            Guid.CreateVersion7(), "Standup", new InboxSource("mobile", Person: null), sourceUrl: null,
            ContentKind.Note, Items.Noon, Items.Noon);

        Assert.Throws<InvalidInboxTransitionException>(() => note.ApplyCaptureEdit("Reworded", null, Edited));
    }
}
